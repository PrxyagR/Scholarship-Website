const catalogErrors = opportunities.flatMap((opportunity) => {
  const errors: string[] = [];
  if (!opportunity.id || !opportunity.title || !opportunity.provider || !opportunity.summary || !opportunity.eligibility) errors.push('missing required text');
  if (!opportunity.applyUrl.startsWith('https://')) errors.push('application URL must use HTTPS');
  if (!opportunity.lastVerified) errors.push('missing verification date');
  if (!opportunity.grades.length || opportunity.grades.some((grade) => grade < 9 || grade > 12)) errors.push('grades must be between 9 and 12');
  if (!supportedProvinces.includes(opportunity.province as (typeof supportedProvinces)[number])) errors.push(`unsupported province: ${opportunity.province}`);
  if (opportunity.studyFocus.some((focus) => !supportedStudyFocuses.includes(focus))) errors.push('unsupported study focus');
  if (opportunity.deadline.kind === 'date' && (!opportunity.deadline.date || opportunity.deadline.date < catalogUpdatedAt)) errors.push('dated deadline is missing or expired');
  return errors.map((error) => `${opportunity.id}: ${error}`);
});

const uniqueIds = new Set(opportunities.map((opportunity) => opportunity.id));
if (uniqueIds.size !== opportunities.length || catalogErrors.length) {
  throw new Error(`Opportunity catalog validation failed: ${[...catalogErrors, uniqueIds.size !== opportunities.length ? 'duplicate opportunity IDs' : ''].filter(Boolean).join('; ')}`);
}
